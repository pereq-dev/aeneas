#!/usr/bin/env bash
# Runs the proof scenario `hax-tests` of the hax test crate `tests/hax` (see
# `tests/hax/hax.toml`) with `cargo hax extract`, using the aeneas and charon of
# this checkout, and builds the extracted Lean code. Also extracts the crates of
# `tests/hax/failures`, which must fail.
#
# Usage:
#   test-hax.sh extract [HAX_DIR]
#       Extract `tests/hax` to Lean, overwriting the committed outputs.
#       Then extract each crate `tests/hax/failures/CRATE`: fails if the
#       extraction succeeds, and records the error output of aeneas in
#       `tests/hax/failures/CRATE.out` (committed). Expects `bin/aeneas`
#       and `charon/bin/charon` to exist.
#   test-hax.sh verify [HAX_DIR]
#       Build the extracted Lean code (`tests/hax/proofs/hax-tests/lean`)
#       against the aeneas Lean library of this checkout and the hax Lean
#       library. Needs `lake` on PATH. Fails if the committed
#       `lean-toolchain` of that project differs from
#       `backends/lean/lean-toolchain`, if an obligation of
#       `Extraction/ProofObligations.lean` has no proof under `Verification/`
#       (commented-out declarations do not count), or if a proof there uses
#       `sorry`.
#
# Where hax comes from:
#   - Without HAX_DIR (or if it is empty), from crates.io: the release of
#     `hax-lib` that the crates resolve to, the `cargo-hax` of the same
#     version (installed with `cargo install` into
#     `tests/hax/.hax-cache/VERSION`), and the hax Lean library shipped in the
#     `hax-lib` package (copied there).
#   - With HAX_DIR, a checkout of https://github.com/cryspen/hax: the crates
#     use its `hax-lib` instead of the one from crates.io, `cargo hax` is
#     taken from PATH (it should be the one of HAX_DIR), and so is the Lean
#     library. HAX_DIR is not modified, except for the Lake build directory
#     of its Lean library.
set -euo pipefail

usage() {
    sed -n '/^# Usage:/,/^set /p' "$0" | sed '$d; s/^# \{0,1\}//' >&2
    exit 1
}

root="$(cd "$(dirname "$0")/.." && pwd)"
tests="$root/tests/hax"
scenario="hax-tests"
lean="$tests/proofs/$scenario/lean"
# The scenario of the crates of `tests/hax/failures` (see their `hax.toml`).
failure_scenario="failure"

# Announces a step, so that the output shows which step the errors that follow
# come from.
step() {
    printf '\n==> %s\n' "$*"
}

# A path relative to the root of this checkout.
rel() {
    echo "${1#"$root/"}"
}

check_hax_dir() {
    [ -d "$1/hax-lib/proof-libs/lean" ] \
        || { echo "error: $1 is not a checkout of hax" >&2; exit 1; }
}

# Warn when the `cargo hax` on PATH is not the version of HAX_DIR: the
# extraction and the libraries would then come from different versions of hax.
check_cargo_hax_version() {
    local hax="$1" expected actual
    expected="$(sed -n '/^\[workspace.package\]/,/^\[/s/^version = "\(.*\)"/\1/p' "$hax/Cargo.toml")"
    actual="$(cargo hax --version | sed -n 's/^version=//p')"
    if [ "$expected" != "$actual" ]; then
        echo "warning: \`cargo hax\` is version $actual but $hax is version $expected" >&2
    fi
}

# Sets up hax, from the checkout HAX_DIR $1 if it is not empty and from
# crates.io otherwise (see the header), and sets:
#   hax_lib_pkgid: the package id that the `hax-lib` of every crate must
#     resolve to (for a checkout, a prefix that the version follows)
#   hax_lean: the hax Lean library
# With $2 = `with-cargo-hax`, also makes sure that `cargo hax` is the one of
# that version of hax.
setup_hax() {
    local cargo_hax="${2:-}"
    if [ -n "$1" ]; then
        local hax
        hax="$(realpath "$1")"
        check_hax_dir "$hax"
        step "Using the hax checkout $hax (HAX_DIR), and \`cargo hax\` from PATH ($(command -v cargo-hax || echo "not found"))"
        [ "$cargo_hax" != with-cargo-hax ] || check_cargo_hax_version "$hax"
        # Use the `hax-lib` of HAX_DIR, which matches its `cargo hax`. Written
        # as a cargo config rather than in the crate's manifest, since the path
        # is machine-specific. It applies to the crates of `tests/hax/failures`
        # too.
        mkdir -p "$tests/.cargo"
        printf '%s\n' '# Generated by scripts/test-hax.sh.' '[patch.crates-io]' \
            "hax-lib = { path = \"$hax/hax-lib\" }" > "$tests/.cargo/config.toml"
        hax_lib_pkgid="path+file://$hax/hax-lib#"
        hax_lean="$hax/hax-lib/proof-libs/lean"
        return
    fi

    # The release of `hax-lib` that the requirement of `tests/hax` resolves
    # to, without the patch to a checkout that a previous run may have left.
    rm -f "$tests/.cargo/config.toml" "$tests/Cargo.lock"
    (cd "$tests" && cargo generate-lockfile --quiet)
    hax_lib_pkgid="$(cd "$tests" && cargo pkgid hax-lib)"
    local version="${hax_lib_pkgid##*#hax-lib@}"
    local cache="$tests/.hax-cache/$version"
    step "Using hax $version from crates.io (HAX_DIR is not set), cached in $(rel "$cache")"

    # `cargo hax` only accepts the `hax-lib` of its own version.
    if [ "$cargo_hax" = with-cargo-hax ]; then
        if [ ! -x "$cache/bin/cargo-hax" ]; then
            step "Installing cargo-hax $version"
            cargo install --locked --root "$cache" "cargo-hax@$version"
        fi
        export PATH="$cache/bin:$PATH"
    fi

    # The `hax-lib` package ships the hax Lean library. It is copied out of
    # Cargo's registry, where Lake would otherwise write its build directory.
    hax_lean="$cache/hax-lean"
    if [ ! -d "$hax_lean" ]; then
        local manifest
        manifest="$(cd "$tests" && cargo metadata --format-version 1 \
                    | grep -o "\"manifest_path\":\"[^\"]*/hax-lib-$version/Cargo.toml\"" \
                    | sed 's/^"manifest_path":"//; s/"$//')"
        [ -n "$manifest" ] \
            || { echo "error: cannot find the sources of hax-lib $version" >&2; exit 1; }
        mkdir -p "$cache"
        rm -rf "$hax_lean.tmp"
        cp -r "$(dirname "$manifest")/proof-libs/lean" "$hax_lean.tmp"
        mv "$hax_lean.tmp" "$hax_lean"
    fi
}

extract() {
    [ $# -le 1 ] || usage
    setup_hax "${1:-}" with-cargo-hax

    # hax expects `charon-driver` next to `charon`.
    local exe
    for exe in "$root/bin/aeneas" "$root/charon/bin/charon" "$root/charon/bin/charon-driver"; do
        [ -x "$exe" ] || { echo "error: $exe is not an executable" >&2; exit 1; }
    done

    resolve_hax_lib "$tests"
    step "Extracting $(rel "$tests") (scenario $scenario)"
    (cd "$tests" && cargo hax extract "$scenario")

    local crate name log
    for crate in "$tests"/failures/*/; do
        crate="${crate%/}"
        name="$(basename "$crate")"
        resolve_hax_lib "$crate"
        # A log left by a previous run would hide a failure before aeneas.
        rm -rf "$crate/proofs"
        step "Extracting $(rel "$crate"), which must fail: the errors below are expected"
        # Shares the build directory of `tests/hax`, so that the dependencies
        # are built once.
        if (cd "$crate" && CARGO_TARGET_DIR="$tests/target" cargo hax extract "$failure_scenario"); then
            echo "error: the extraction of ${crate#"$root/"} succeeded, but must fail" >&2
            exit 1
        fi
        log="$crate/proofs/$failure_scenario/lean/aeneas-error.log"
        [ -f "$log" ] || { echo "error: ${crate#"$root/"} failed before running aeneas" >&2; exit 1; }
        # Without colors, timings, OCaml backtraces (their line numbers change
        # with any edit) and the machine-specific paths.
        sed -e $'s/\x1b\\[[0-9;]*m//g' -e "s|$crate/||g" -e '/^\[Info *\] Total execution time:/d' \
            -e '/^Raised at /d' -e '/^Called from /d' \
            "$log" > "$tests/failures/$name.out"
        echo "$(rel "$crate") failed as expected: its error is in $(rel "$tests/failures/$name.out")"
    done

    step "OK: extracted $(rel "$tests"), and each crate of $(rel "$tests/failures") failed as expected." \
        "Check the changes to the committed outputs with \`git diff $(rel "$tests")\`."
}

# Checks that the `hax-lib` dependency of the crate in directory $1 resolves to
# the one chosen by `setup_hax`, resolving from scratch (the lockfile may
# predate the patch to HAX_DIR, or a new release). With HAX_DIR, Cargo ignores
# the patch, with a mere warning, when the version of HAX_DIR does not satisfy
# the `hax-lib` requirement of the crate, and falls back to crates.io. Without,
# the crates could require different releases.
resolve_hax_lib() {
    local crate="$1" pkgid
    rm -f "$crate/Cargo.lock"
    (cd "$crate" && cargo generate-lockfile --quiet)
    pkgid="$(cd "$crate" && cargo pkgid hax-lib)"
    case "$pkgid" in
        "$hax_lib_pkgid"*) ;;
        *)
            echo "error: \`hax-lib\` resolves to $pkgid instead of $hax_lib_pkgid:" \
                "update the \`hax-lib\` requirement of ${crate#"$root/"}/Cargo.toml" >&2
            exit 1
            ;;
    esac
}

# The names declared by `theorem` in the given Lean files, or in stdin if none
# (the name may be on the line after `theorem`). Lean comments (`--` to the end
# of the line, nested `/- … -/` blocks, docstrings included) are skipped, so a
# commented-out proof does not count.
declared_theorems() {
    awk '
        FNR == 1 { depth = 0; want = 0 }
        {
            line = ""; i = 1; n = length($0)
            while (i <= n) {
                two = substr($0, i, 2)
                if (depth > 0) {
                    if (two == "/-") { depth++; i += 2 }
                    else if (two == "-/") { depth--; i += 2; if (depth == 0) line = line " " }
                    else i++
                } else if (two == "/-") { depth = 1; i += 2; line = line " " }
                else if (two == "--") break
                else { line = line substr($0, i, 1); i++ }
            }
            m = split(line, tok, /[ \t]+/)
            for (j = 1; j <= m; j++) {
                if (tok[j] == "") continue
                if (want) { print tok[j]; want = 0 } else if (tok[j] == "theorem") want = 1
            }
        }' "$@" | sort -u
}

verify() {
    [ $# -le 1 ] || usage
    setup_hax "${1:-}"
    ln -sfn "$hax_lean" "$lean/.hax-lean"
    if ! cmp -s "$root/backends/lean/lean-toolchain" "$lean/lean-toolchain"; then
        echo "error: ${lean#"$root/"}/lean-toolchain differs from backends/lean/lean-toolchain:" \
            "copy it over and commit it" >&2
        exit 1
    fi
    # Global, not `local`: the EXIT trap runs after `verify` has returned,
    # where a local would be unbound (`set -u`).
    log="$(mktemp)"
    trap 'rm -f "$log"' EXIT
    step "Building $(rel "$lean")"
    (cd "$lean" && lake update && lake exe cache get && lake build 2>&1 | tee "$log")
    step "Checking the proofs under Verification/: one per obligation, without \`sorry\`"
    # A proof under `Verification/` must not use `sorry` (Lake replays the
    # warnings of up-to-date modules, so this also holds on rebuilds). Filtered
    # by file: the template of the obligations is all `sorry`.
    if grep -E 'HaxTests/Verification/[^:]*\.lean:[0-9]+:[0-9]+: declaration uses .sorry.' "$log" >&2; then
        echo "error: proofs in Verification/ use \`sorry\`" >&2
        exit 1
    fi
    # Every obligation of the template must be proved under `Verification/`
    # (the proofs may be split across files there).
    local obligations missing
    obligations="$(declared_theorems "$lean/HaxTests/Extraction/ProofObligations.lean")"
    missing="$(comm -23 <(echo "$obligations") \
                        <(find "$lean/HaxTests/Verification" -name '*.lean' -exec cat {} + | declared_theorems))"
    if [ -n "$missing" ]; then
        echo "error: obligations of Extraction/ProofObligations.lean without a proof in Verification/:" >&2
        echo "$missing" >&2
        exit 1
    fi

    step "OK: $(rel "$lean") builds, and its $(echo "$obligations" | grep -c .) obligations are proved without \`sorry\`."
}

[ $# -ge 1 ] || usage
command="$1"
shift
case "$command" in
    extract) extract "$@" ;;
    verify) verify "$@" ;;
    *) usage ;;
esac
